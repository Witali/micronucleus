#!/usr/bin/env python3
"""Import the pinned official ATtiny88 definitions and adapt AVRASM equates.

No download is performed here. --pack accepts the Microchip archive downloaded
from PACK_URL. Without --pack the checked-in original is sufficient to rebuild
or check the GNU/LLVM include offline.
"""
from pathlib import Path
import argparse
import hashlib
import re
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT/'vendor/microchip/ATtiny_DFP-3.4.278'
PACK_URL = 'https://packs.download.microchip.com/Microchip.ATtiny_DFP.3.4.278.atpack'
PACK_SHA256 = '41f09d5825abaa764c9000f4488f8ba3fab152afe6229b359de4a5efe9a21eda'
SOURCE_SHA256 = '4c516f34d159f97fb1a253c91dec01d456d05cc4fa80f13c15728a08366bff7d'
LICENSE_SHA256 = '3bf0a101f2b2e44eda3b477f866bd24204c35fa1f841c865933028adf155336a'


def gas_include(original):
    """Translate every .equ NAME = value without changing names or values."""
    assert hashlib.sha256(original).hexdigest() == SOURCE_SHA256, 'Official source hash mismatch'
    definitions = []
    for line in original.decode('utf-8-sig').splitlines():
        if not line.startswith('.equ'):
            continue
        match = re.fullmatch(r'\.equ\s+([A-Za-z_][A-Za-z_0-9]*)\s*=\s*([^;]+)(?:;.*)?', line)
        assert match, f'Unsupported AVRASM equate: {line}'
        name, expression = match.groups()
        definitions.append((name, expression.strip()))
    assert len(definitions) == len(dict(definitions)) == 585
    header = ('/* Generated from Microchip ATtiny_DFP 3.4.278 avrasm/inc/tn88def.inc.\n'
              ' * Source SHA-256: '+SOURCE_SHA256+'\n'
              ' * Copyright Microchip Technology Inc. See LICENSE.txt and LICENSE-APACHE-2.0.txt.\n'
              ' * Generated by tools/import_microchip_device.py; do not edit.\n'
              ' * Only .equ definitions are imported. AVRASM device/IDE directives\n'
              ' * and .def CPU-register aliases are omitted; use r26-r31 or X/Y/Z.\n'
              ' * I/O registers use IN/OUT addresses; extended registers use data addresses.\n'
              ' * FLASHEND and PAGESIZE are in words; RAMEND and E2END are byte addresses.\n'
              ' */\n#ifndef T88_MICROCHIP_GAS_INC\n#define T88_MICROCHIP_GAS_INC\n')
    return header + ''.join(f'.equ {name}, {value}\n' for name, value in definitions) + '#endif\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pack', type=Path, help='Official pinned .atpack archive')
    parser.add_argument('--check', action='store_true', help='Check the generated include without rewriting it')
    args = parser.parse_args()
    if args.pack:
        assert not args.check, 'Use --pack to import or --check to verify'
        assert hashlib.sha256(args.pack.read_bytes()).hexdigest() == PACK_SHA256, 'Pack hash mismatch'
        with ZipFile(args.pack) as archive:
            original = archive.read('avrasm/inc/tn88def.inc')
            license_notice = archive.read('LICENSE.txt')
        assert hashlib.sha256(license_notice).hexdigest() == LICENSE_SHA256
        assert hashlib.sha256(original).hexdigest() == SOURCE_SHA256
        VENDOR.mkdir(parents=True, exist_ok=True)
        (VENDOR/'tn88def.inc').write_bytes(original)
        (VENDOR/'LICENSE.txt').write_bytes(license_notice)
    generated = gas_include((VENDOR/'tn88def.inc').read_bytes()).encode()
    destination = VENDOR/'tn88def-gas.inc'
    if args.check:
        assert destination.read_bytes() == generated, 'Regenerate tn88def-gas.inc'
    else:
        destination.write_bytes(generated)
    print('PASS: pinned Microchip ATtiny88 source; 585 equates reproduced without numeric changes')


if __name__ == '__main__':
    main()
